/*
 * Frame profiler (compat/port_prof.h). Sections add their ticks to the frame
 * being made; at present the frame is reported and cleared. A frame that took
 * longer than the display allows is logged whole, section by section, with
 * the screen it was on, and every few seconds the averages are logged: which
 * part of the engine a hitch came from is then in the SD log.
 *
 * Every frame is also one fixed-size record in perf.bin (3ds_log.c), with
 * what the frame was, how it was drawn and where its time went; and frames
 * are gathered into segments - one screen in one mode - whose percentiles,
 * missed VBlanks and 3D losses are logged when the segment ends (PERF lines).
 * scripts/perf_report.py reads both. The boot log says which executable made
 * them (CtrProf_LogIdentity): the baseline of phase F0.
 */
#include <3ds.h>
#include <math.h>
#include <stdio.h>
#include <string.h>

#include "3ds_platform.h"
#include "3ds_video.h"
#include "3ds_gpumem.h"
#include "3ds_map_events.h"
#include "3ds_sprite_ids.h"
#include "voxel/ctr_voxel.h"
#include "../compat/port_prof.h"

/* A frame over this much work is logged on its own (the display gives 16.7). */
#define PROF_SLOW_MS 15.0f
#define PROF_SLOW_LINES 4000
#define PROF_AVERAGE_FRAMES 300

static uint32_t sFrame[PORT_PROF_COUNT];
static uint64_t sSum[PORT_PROF_COUNT];
static float sWorkSum, sWorkPeak;
static unsigned sFrames, sSlowLines;
static uintptr_t sScene;
/* Sections timed this frame: each is two reads of the system tick, which is
 * a system call - the profiler's own cost (sTickCost, measured at boot). */
static unsigned sCalls;
static float sTickCost;

static const char *const sNames[PORT_PROF_COUNT] = {
    "task", "spr", "fade", "vbl", "vcb", "dma3", "mix",
    "io", "lz", "copy", "lines", "pal", "lay", "draw", "end",
    "bw.world", "bw.post", "bw.scene",
    "bs.prep", "bs.slots", "bs.text", "bs.eyes", "bs.whole",
    "bottom", "stmon", "vox.bat",
};

/* Only when there is a log to report to: every section is two tick reads,
 * and the engine's copies alone are hundreds of sections a frame. */
static int sOn = -1;

static bool ProfOn(void)
{
    if (sOn < 0)
        sOn = CtrLog_Enabled();
    return sOn;
}

uint32_t Port_ProfTick(void)
{
    return ProfOn() ? (uint32_t)svcGetSystemTick() : 0;
}

void Port_ProfAdd(unsigned section, uint32_t start)
{
    if (ProfOn() && section < PORT_PROF_COUNT)
    {
        sFrame[section] += (uint32_t)svcGetSystemTick() - start;
        ++sCalls;
    }
}

void Port_ProfScene(const void *callback2)
{
    sScene = (uintptr_t)callback2;
}

uintptr_t CtrProf_Scene(void)
{
    return sScene;
}

static int Sections(char *text, size_t size, const uint32_t *ticks, const uint64_t *sums, unsigned frames)
{
    int used = 0;

    for (unsigned i = 0; i < PORT_PROF_COUNT && used < (int)size; ++i)
    {
        float ms = sums ? (float)(sums[i] * 1000.0 / SYSCLOCK_ARM11 / frames)
                        : (float)(ticks[i] * 1000.0 / SYSCLOCK_ARM11);

        if (ms >= 0.05f)
            used += snprintf(text + used, size - used, " %s=%.2f", sNames[i], ms);
    }
    return used;
}

/* ── Identity ─────────────────────────────────────────────────────────────
 * build/buildinfo.c, generated by the Makefile. */
extern const char gCtrBuildVersion[], gCtrBuildCommit[], gCtrBuildBranch[], gCtrBuildDiff[];
extern const char gCtrBuildLibs[], gCtrBuildDefines[], gCtrBuildCompiler[];
/* build/linkid.c: different at every link. */
extern const char gCtrLinkId[];
extern const unsigned gCtrBuildDirty;
extern const uint32_t __ctr_text_start[], __ctr_text_end[];

/* FNV-1a over the code as loaded, a word at a time; perf_report.py --elf
 * computes the same over the ELF's .text. */
static uint64_t CodeHash(void)
{
    uint64_t hash = 0xcbf29ce484222325ull;

    for (const uint32_t *word = __ctr_text_start; word < __ctr_text_end; ++word)
        hash = (hash ^ *word) * 0x100000001b3ull;
    return hash;
}

static const char *ModelName(u8 model)
{
    static const char *const names[] = {"Old 3DS", "Old 3DS XL", "New 3DS", "Old 2DS", "New 3DS XL", "New 2DS XL"};

    return model < sizeof(names) / sizeof(names[0]) ? names[model] : "unknown";
}

/* perf.bin begins with one header, then a CtrPerfRecord per frame. */
#define PERF_MAGIC 0x46503345u   /* "E3PF" */
#define PERF_VERSION 1

enum
{
    T_READY, T_GAME, T_BOTTOM, T_VBLANK, T_PRESENT, T_PREP, T_WAIT, T_GPU, T_GPU_START,
    T_GAP, T_ARRIVE, T_PALETTE, T_LAYERS, T_DRAW, T_FRAMEEND, T_VOXEL, T_VOXEL_AFTER,
    T_STEREO_SAMPLE, T_STEREO_EYES, T_TASKS, T_SPRITES, T_MIX, T_LOAD, T_PROFILER,
    T_COUNT
};

typedef struct
{
    uint32_t frame, scene;
    uint8_t mode, route, sliderPct, stereo;
    uint8_t flat, missed, flags, reserved;
    uint16_t t[T_COUNT];    /* units of 10 microseconds */
} CtrPerfRecord;
_Static_assert(sizeof(CtrPerfRecord) == 64, "perf.bin record");

typedef struct
{
    uint32_t magic, version, recordSize, timings;
    char commit[40];
    char diff[12];
    uint32_t dirty, codeLow, codeHigh, model;
    char appVersion[8];
    char linkId[24];
    uint8_t reserved[12];
} CtrPerfHeader;
_Static_assert(sizeof(CtrPerfHeader) == 128, "perf.bin header");

static u8 sModel = 0xff;

void CtrProf_LogIdentity(void)
{
    CtrPerfHeader header;
    uint64_t code, start;
    float ms;

    if (!ProfOn())
        return;
    if (R_SUCCEEDED(cfguInit()))
    {
        CFGU_GetSystemModel(&sModel);
        cfguExit();
    }
    start = svcGetSystemTick();
    code = CodeHash();
    ms = (svcGetSystemTick() - start) * 1000.0f / SYSCLOCK_ARM11;
    CtrLog_Write(CTR_LOG_BOOT, "BUILD %s version=%s commit=%s branch=%s dirty=%u diff=%s", gCtrLinkId,
                 gCtrBuildVersion, gCtrBuildCommit, gCtrBuildBranch, gCtrBuildDirty, gCtrBuildDiff);
    CtrLog_Write(CTR_LOG_BOOT, "BUILD code=%016llx text=%lu (hashed in %.1f ms) gcc=%s %s",
                 (unsigned long long)code,
                 (unsigned long)((__ctr_text_end - __ctr_text_start) * 4), ms,
                 gCtrBuildCompiler, gCtrBuildLibs);
    CtrLog_Write(CTR_LOG_BOOT, "BUILD defines=%s", gCtrBuildDefines);
    CtrLog_Write(CTR_LOG_BOOT, "SYSTEM model=%s (%u) new3ds=%d kernel=%lu.%lu-%lu firm=%lu.%lu-%lu slider=%.2f",
                 ModelName(sModel), sModel, sModel == 2 || sModel == 4 || sModel == 5,
                 (unsigned long)GET_VERSION_MAJOR(osGetKernelVersion()),
                 (unsigned long)GET_VERSION_MINOR(osGetKernelVersion()),
                 (unsigned long)GET_VERSION_REVISION(osGetKernelVersion()),
                 (unsigned long)GET_VERSION_MAJOR(osGetFirmVersion()),
                 (unsigned long)GET_VERSION_MINOR(osGetFirmVersion()),
                 (unsigned long)GET_VERSION_REVISION(osGetFirmVersion()), osGet3DSliderState());
    /* What one timed section costs the frame: two system calls. */
    start = svcGetSystemTick();
    for (unsigned i = 0; i < 1000; ++i)
        svcGetSystemTick();
    sTickCost = (svcGetSystemTick() - start) * 1000.0f / SYSCLOCK_ARM11 / 1000.0f;
    CtrLog_Write(CTR_LOG_BOOT, "PERF tick read=%.2f us; perf.bin records of %u bytes, %u timings",
                 sTickCost * 1000.0f, (unsigned)sizeof(CtrPerfRecord), (unsigned)T_COUNT);

    memset(&header, 0, sizeof(header));
    header.magic = PERF_MAGIC;
    header.version = PERF_VERSION;
    header.recordSize = sizeof(CtrPerfRecord);
    header.timings = T_COUNT;
    memcpy(header.commit, gCtrBuildCommit, strnlen(gCtrBuildCommit, sizeof(header.commit)));
    memcpy(header.diff, gCtrBuildDiff, strnlen(gCtrBuildDiff, sizeof(header.diff)));
    header.dirty = gCtrBuildDirty;
    header.codeLow = (uint32_t)code;
    header.codeHigh = (uint32_t)(code >> 32);
    header.model = sModel;
    memcpy(header.linkId, gCtrLinkId, strnlen(gCtrLinkId, sizeof(header.linkId)));
    memcpy(header.appVersion, gCtrBuildVersion, strnlen(gCtrBuildVersion, sizeof(header.appVersion)));
    CtrLog_WriteBinary(&header, sizeof(header));
}

/* ── Segments ─────────────────────────────────────────────────────────────
 * One screen (callback2) in one mode. Short segments - a fade, a transition -
 * are only in perf.bin; long ones are cut every SEGMENT_MAX frames so that
 * a measured stretch of 6000 frames is one line. */
#define SEGMENT_MIN 120
#define SEGMENT_MAX 6000
#define BINS 500            /* 0.1 ms each, up to 50 ms */

static const char *const sModes[CTR_MODE_COUNT] = {
    "other", "field", "voxel", "battle", "voxel-battle", "stage", "centred", "bottom",
};

static struct
{
    uint32_t scene, first, last, frames;
    uint8_t mode;
    uint16_t ready[BINS], gpuEnd[BINS];
    float readyMax, gpuEndMax;
    uint32_t missed, missedFrames, slider, stereo, flat[8];
    double sum[T_COUNT];
} sSeg;

static float Percentile(const uint16_t *bins, unsigned frames, float fraction)
{
    unsigned target = (unsigned)ceilf(frames * fraction), seen = 0;

    for (unsigned i = 0; i < BINS; ++i)
        if ((seen += bins[i]) >= target)
            return (i + 1) * 0.1f;
    return BINS * 0.1f;
}

static void SegmentReport(void)
{
    unsigned n = sSeg.frames;
    double *s = sSeg.sum;

    if (n < SEGMENT_MIN)
        return;
#define M(i) (float)(s[i] / n / 100.0)
    CtrLog_Write(CTR_LOG_VIDEO, "PERF seg %s cb2=%08lx f=%lu-%lu n=%u ready p50=%.2f p95=%.2f p99=%.2f max=%.2f"
                 " | gpuEnd p50=%.2f p95=%.2f p99=%.2f max=%.2f | missed=%lu in %lu frames",
                 sModes[sSeg.mode], (unsigned long)sSeg.scene, (unsigned long)sSeg.first,
                 (unsigned long)sSeg.last, n,
                 Percentile(sSeg.ready, n, 0.5f), Percentile(sSeg.ready, n, 0.95f),
                 Percentile(sSeg.ready, n, 0.99f), sSeg.readyMax,
                 Percentile(sSeg.gpuEnd, n, 0.5f), Percentile(sSeg.gpuEnd, n, 0.95f),
                 Percentile(sSeg.gpuEnd, n, 0.99f), sSeg.gpuEndMax,
                 (unsigned long)sSeg.missed, (unsigned long)sSeg.missedFrames);
    CtrLog_Write(CTR_LOG_VIDEO, "PERF seg means game=%.2f (bottom=%.2f task=%.2f spr=%.2f load=%.2f) vblank=%.2f"
                 " prep=%.2f present=%.2f (pal=%.2f lay=%.2f draw=%.2f end=%.2f) gpu=%.2f gpuStart=%.2f"
                 " voxel=%.2f after=%.2f stereo sample=%.2f eyes=%.2f mix=%.2f profiler=%.3f",
                 M(T_GAME), M(T_BOTTOM), M(T_TASKS), M(T_SPRITES), M(T_LOAD), M(T_VBLANK), M(T_PREP),
                 M(T_PRESENT), M(T_PALETTE), M(T_LAYERS), M(T_DRAW), M(T_FRAMEEND), M(T_GPU),
                 M(T_GPU_START), M(T_VOXEL), M(T_VOXEL_AFTER), M(T_STEREO_SAMPLE), M(T_STEREO_EYES),
                 M(T_MIX), M(T_PROFILER));
#undef M
    CtrLog_Write(CTR_LOG_VIDEO, "PERF seg 3D slider up in %lu frames, 3D shown in %lu; whole per eye: blend=%lu "
                 "mosaic=%lu bg-front=%lu slots=%lu; flat: voxel-off=%lu no-surface=%lu no-planes=%lu other=%lu",
                 (unsigned long)sSeg.slider, (unsigned long)sSeg.stereo,
                 (unsigned long)sSeg.flat[0], (unsigned long)sSeg.flat[1], (unsigned long)sSeg.flat[2],
                 (unsigned long)sSeg.flat[3], (unsigned long)sSeg.flat[4], (unsigned long)sSeg.flat[5],
                 (unsigned long)sSeg.flat[6], (unsigned long)sSeg.flat[7]);
    {
        uint32_t c[8];

        CtrVideo_DecodeCounts(c);
        CtrLog_Write(CTR_LOG_VIDEO, "PERF seg tiles decoded %lu in %lu frames (new %lu, bytes %lu, palette %lu, "
                     "same as before, kept %lu); layer cells redrawn %lu in %lu frames",
                     (unsigned long)c[7], (unsigned long)c[4], (unsigned long)c[0], (unsigned long)c[1],
                     (unsigned long)c[2], (unsigned long)c[3], (unsigned long)c[6], (unsigned long)c[5]);
    }
}

static uint16_t Units(float ms)
{
    float units = ms * 100.0f + 0.5f;

    return units <= 0.0f ? 0 : units >= 65535.0f ? 65535 : (uint16_t)units;
}

static void Bin(uint16_t *bins, float ms)
{
    int bin = (int)(ms * 10.0f);

    bins[bin < 0 ? 0 : bin >= BINS ? BINS - 1 : bin]++;
}

static float Ms(uint32_t ticks)
{
    return ticks * 1000.0f / SYSCLOCK_ARM11;
}

/* One frame into perf.bin and its segment. */
static void Record(float workMs, float waitMs, uint64_t frame, float profilerMs)
{
    const CtrTiming *timing = CtrPlatform_GetTiming();
    const CtrVideoStats *video = CtrVideo_GetStats();
    const CtrVoxelStats *voxel = CtrVoxel_GetStats();
    CtrPerfRecord r;
    /* FrameBegin read the last frame's drawing time: it ended that long
     * after the last frame set the GPU going. (The record keeps both as
     * read; perf_report.py pairs them the same way.) */
    static float sLastGpuStart;
    float gpuEnd = sLastGpuStart + video->gpuMs;

    sLastGpuStart = video->gpuStartMs;
    unsigned missed = video->gapMs > 0.0f ? (unsigned)((video->gapMs + 8.35f) / 16.7f) : 1;

    missed = missed > 0 ? missed - 1 : 0;
    memset(&r, 0, sizeof(r));
    r.frame = (uint32_t)frame;
    r.scene = (uint32_t)sScene;
    r.mode = video->mode;
    r.route = video->route;
    r.sliderPct = video->sliderPct;
    r.stereo = video->stereo > 255 ? 255 : (uint8_t)video->stereo;
    r.flat = video->flat;
    r.missed = missed > 255 ? 255 : (uint8_t)missed;
    r.flags = (video->voxelFrame ? 1 : 0) | (CtrScenario_Playing() ? 2 : 0) | (CtrSettings_Speed() > 1 ? 4 : 0);
    r.t[T_READY] = Units(workMs);
    r.t[T_GAME] = Units(timing->gameMs);
    r.t[T_BOTTOM] = Units(timing->bottomMs);
    r.t[T_VBLANK] = Units(timing->vblankMs);
    r.t[T_PRESENT] = Units(video->cpuMs);
    r.t[T_PREP] = Units(video->prepMs);
    r.t[T_WAIT] = Units(waitMs);
    r.t[T_GPU] = Units(video->gpuMs);
    r.t[T_GPU_START] = Units(video->gpuStartMs);
    r.t[T_GAP] = Units(video->gapMs);
    r.t[T_ARRIVE] = Units(video->arriveMs);
    r.t[T_PALETTE] = Units(Ms(sFrame[PORT_PROF_PALETTE]));
    r.t[T_LAYERS] = Units(Ms(sFrame[PORT_PROF_LAYERS]));
    r.t[T_DRAW] = Units(Ms(sFrame[PORT_PROF_DRAW]));
    r.t[T_FRAMEEND] = Units(Ms(sFrame[PORT_PROF_FRAMEEND]));
    if (video->voxelFrame)
    {
        r.t[T_VOXEL] = Units(voxel->updateMs);
        r.t[T_VOXEL_AFTER] = Units(voxel->afterMs);
    }
    r.t[T_STEREO_SAMPLE] = Units(video->stereoSampleMs);
    r.t[T_STEREO_EYES] = Units(video->stereoEyesMs);
    r.t[T_TASKS] = Units(Ms(sFrame[PORT_PROF_TASKS]));
    r.t[T_SPRITES] = Units(Ms(sFrame[PORT_PROF_SPRITES]));
    r.t[T_MIX] = Units(Ms(sFrame[PORT_PROF_MIX]));
    r.t[T_LOAD] = Units(Ms(sFrame[PORT_PROF_IO] + sFrame[PORT_PROF_LZ]));
    r.t[T_PROFILER] = Units(profilerMs);
    CtrLog_WriteBinary(&r, sizeof(r));

    /* The segment: a new one at a change of screen or mode, or when full. */
    if (sSeg.frames != 0 && (sSeg.scene != r.scene || sSeg.mode != r.mode || sSeg.frames >= SEGMENT_MAX))
    {
        bool changed = sSeg.scene != r.scene || sSeg.mode != r.mode;

        SegmentReport();
        if (changed && sSeg.frames >= SEGMENT_MIN)
        {
            uint32_t chunkUsed, chunkGap, pageUsed, pageGap;

            CtrGpuMem_Report(sModes[sSeg.mode]);
            CtrVoxel_ArenaUse(&chunkUsed, &chunkGap, &pageUsed, &pageGap);
            CtrLog_Write(CTR_LOG_VIDEO, "GPUMEM voxel arenas: chunks used=%luK largest gap=%luK, "
                         "building pages used=%luK largest gap=%luK%s",
                         (unsigned long)(chunkUsed >> 10), (unsigned long)(chunkGap >> 10),
                         (unsigned long)(pageUsed >> 10), (unsigned long)(pageGap >> 10),
                         CtrVoxel_HoldsVram() ? "" : " (parked)");
            {
                uint32_t cells, collision, reloads;

                CtrMap_Counts(&cells, &collision, &reloads);
                CtrLog_Write(CTR_LOG_VIDEO, "MAP changes announced: %lu cells, %lu collision only, %lu reloads",
                             (unsigned long)cells, (unsigned long)collision, (unsigned long)reloads);
            }
        }
        memset(&sSeg, 0, sizeof(sSeg));
    }
    if (sSeg.frames == 0)
    {
        sSeg.scene = r.scene;
        sSeg.mode = r.mode;
        sSeg.first = r.frame;
    }
    sSeg.last = r.frame;
    sSeg.frames++;
    Bin(sSeg.ready, workMs);
    Bin(sSeg.gpuEnd, gpuEnd);
    if (workMs > sSeg.readyMax) sSeg.readyMax = workMs;
    if (gpuEnd > sSeg.gpuEndMax) sSeg.gpuEndMax = gpuEnd;
    sSeg.missed += missed;
    sSeg.missedFrames += missed != 0;
    sSeg.slider += r.sliderPct > 2;
    sSeg.stereo += r.stereo != 0;
    for (unsigned i = 0; i < 8; ++i)
        sSeg.flat[i] += (r.flat >> i) & 1;
    for (unsigned i = 0; i < T_COUNT; ++i)
        sSeg.sum[i] += r.t[i];
}

void CtrProf_EndFrame(float workMs, float waitMs, uint64_t frame)
{
    char text[400];
    uint64_t start;

    if (!ProfOn())
        return;
    start = svcGetSystemTick();
    if (workMs > PROF_SLOW_MS && sSlowLines < PROF_SLOW_LINES)
    {
        ++sSlowLines;
        Sections(text, sizeof(text), sFrame, NULL, 0);
        CtrLog_Write(CTR_LOG_VIDEO, "PROF slow f=%llu cb2=%08lx work=%.2f wait=%.2f game=%.2f:%s",
                     (unsigned long long)frame, (unsigned long)sScene, workMs, waitMs,
                     CtrPlatform_GetTiming()->gameMs, text);
    }
    /* The profiler's own cost: the sections' tick reads, and this. */
    {
        static float sLastOwnMs;

        Record(workMs, waitMs, frame, sCalls * 2 * sTickCost + sLastOwnMs);
        sCalls = 0;
        sLastOwnMs = Ms((uint32_t)(svcGetSystemTick() - start));
    }
    for (unsigned i = 0; i < PORT_PROF_COUNT; ++i)
        sSum[i] += sFrame[i];
    memset(sFrame, 0, sizeof(sFrame));
    sWorkSum += workMs;
    if (workMs > sWorkPeak) sWorkPeak = workMs;
    if (++sFrames == PROF_AVERAGE_FRAMES)
    {
        Sections(text, sizeof(text), NULL, sSum, sFrames);
        CtrLog_Write(CTR_LOG_VIDEO, "PROF avg f=%llu cb2=%08lx work=%.2f peak=%.2f:%s",
                     (unsigned long long)frame, (unsigned long)sScene, sWorkSum / sFrames,
                     sWorkPeak, text);
        memset(sSum, 0, sizeof(sSum));
        sWorkSum = sWorkPeak = 0.0f;
        sFrames = 0;
    }
}

/* The last segment, at exit. */
void CtrProf_Close(void)
{
    if (!ProfOn())
        return;
    SegmentReport();
    CtrGpuMem_Report("exit");
    CtrSprites_Report();
}
